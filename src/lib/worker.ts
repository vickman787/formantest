import JSZip from "jszip";
import { getPool } from "./db";
import { saveArtifact } from "./artifacts";
import { APP_MODE } from "./config";
import { addEvent, claimNextQueued, getOrder, setStep, updateOrder, type OrderRow } from "./jobs";
import { buildManifest, type ManifestFile } from "./manifest";
import { generateWebsiteCopy, openaiConfigured, researchMarket } from "./openai";
import { renderFlyer } from "./renderers/flyer";
import { renderReport } from "./renderers/report";
import { renderVideo } from "./renderers/video";
import { renderWebsite } from "./renderers/website";

/**
 * Durable worker: validate → generate → render → check → deliver.
 * Every stage is persisted in Postgres (job_steps + order_events), so a
 * restart resumes from the last saved stage instead of redoing paid work.
 * Demo mode uses our own template renderers and moves no money.
 * Live mode needs verified funding first — the API never queues a live
 * job before payment-sync confirms the escrow receipt.
 */

async function recordArtifacts(orderId: string, version: number, files: { filename: string; mime: string; data: Buffer | string }[]): Promise<ManifestFile[]> {
  const out: ManifestFile[] = [];
  for (const f of files) {
    const saved = await saveArtifact(orderId, f.filename, f.mime, f.data);
    await getPool().query(
      "INSERT INTO artifacts(id, order_id, version, filename, mime, size_bytes, sha256, storage_key) VALUES ($1,$2,$3,$4,$5,$6,$7,$8) ON CONFLICT (order_id, version, filename) DO NOTHING",
      [`art_${orderId}_${version}_${saved.filename}`, orderId, version, saved.filename, saved.mime, saved.size_bytes, saved.sha256, saved.storage_key],
    );
    out.push({ filename: saved.filename, mime: saved.mime, size_bytes: saved.size_bytes, sha256: saved.sha256 });
  }
  return out;
}

export async function processOrder(order: OrderRow): Promise<void> {
  const brief = order.brief as Record<string, unknown>;
  try {
    await setStep(order.id, "validate", "done", "Brief validated against the service schema.");
    await addEvent(order.id, "validated", "Brief validated. Generation started.");
    await setStep(order.id, "generate", "running", "Writing copy from the brief.");

    let files: { filename: string; mime: string; data: Buffer | string }[] = [];
    let checks: { name: string; passed: boolean; detail: string }[] = [];
    let extraNote = "";
    let researchNote = "";

    if (order.service === "business_website") {
      let headline: string | undefined;
      if (APP_MODE === "live" && openaiConfigured()) {
        const copy = await generateWebsiteCopy(brief);
        headline = copy.headline;
      }
      const { html, checks: c } = renderWebsite(brief as never, { headline });
      checks = c;
      const zip = new JSZip();
      zip.file("index.html", html);
      zip.file("README.txt", `Website for ${brief.business_name}.\nOpen index.html in any browser. No backend needed.\nGenerated by Forma (demo template renderer${APP_MODE === "live" ? " + OpenAI copy" : ""}).\n`);
      const zipBuf = await zip.generateAsync({ type: "nodebuffer" });
      files = [
        { filename: "index.html", mime: "text/html", data: html },
        { filename: "website-source.zip", mime: "application/zip", data: zipBuf },
      ];
    } else if (order.service === "flyers_price_list") {
      const { png, flyerPdf, priceListPdf, checks: c } = await renderFlyer(brief as never);
      checks = c;
      files = [
        { filename: "flyer.png", mime: "image/png", data: png },
        { filename: "flyer.pdf", mime: "application/pdf", data: flyerPdf },
        { filename: "price-list.pdf", mime: "application/pdf", data: priceListPdf },
      ];
    } else if (order.service === "promo_video") {
      const { mp4, poster, captions, checks: c } = await renderVideo(brief as never);
      checks = c;
      files = [
        { filename: "promo-vertical.mp4", mime: "video/mp4", data: mp4 },
        { filename: "poster.jpg", mime: "image/jpeg", data: poster },
        { filename: "captions.txt", mime: "text/plain", data: captions },
      ];
    } else if (order.service === "market_report") {
      // Cited report: one paid web-research call, then our own renderer.
      // No key, no report — the job fails honestly instead of faking one.
      const research = await researchMarket(brief as Record<string, unknown>);
      const retrievedAt = new Date().toISOString().slice(0, 10);
      const report = renderReport(brief as never, research.text, retrievedAt);
      checks = report.checks;
      researchNote = `Research ${research.requestId ?? "no id"} · ${report.sources.length} source(s)` +
        (research.usage ? ` · ${research.usage.input_tokens} in / ${research.usage.output_tokens} out tokens` : "");
      files = [
        { filename: "market-report.html", mime: "text/html", data: report.html },
        { filename: "market-report.pdf", mime: "application/pdf", data: report.pdf },
        { filename: "sources.csv", mime: "text/csv", data: report.csv },
      ];
    } else {
      throw new Error(`Unknown service ${order.service}`);
    }

    await setStep(order.id, "generate", "done", researchNote ? `Draft built from the brief. ${researchNote}` : "Draft built from the brief.");
    await setStep(order.id, "render", "done", `${files.length} file(s) rendered.`);
    await addEvent(order.id, "rendered", "Draft rendered. Running quality checks.");

    await setStep(order.id, "check", "running", "Verifying prices, contact and formats.");
    const failed = checks.filter((c) => !c.passed);
    if (failed.length > 0) {
      throw new Error(`Quality check failed: ${failed.map((f) => f.name).join(", ")}`);
    }
    await setStep(order.id, "check", "done", `All ${checks.length} checks passed.`);
    extraNote = APP_MODE === "demo" ? "Demo mode: template-rendered from your brief, no funds moved." : "";

    const manifestFiles = await recordArtifacts(order.id, 1, files);
    const { manifest, hash } = buildManifest({
      service: order.service,
      order_id: order.id,
      version: 1,
      files: manifestFiles,
      checks,
      created_at: new Date().toISOString(),
    });
    await updateOrder(order.id, {
      state: "delivered",
      manifest_hash: hash,
      manifest: manifest as unknown as Record<string, unknown>,
      review_deadline: new Date(Date.now() + 48 * 60 * 60 * 1000).toISOString(),
    });
    await setStep(order.id, "deliver", "done", `Delivery v1 ready. Manifest ${hash.slice(0, 12)}… ${extraNote}`);
    await addEvent(order.id, "delivered", `Delivery ready for review. ${extraNote}`);
  } catch (e) {
    const message = e instanceof Error ? e.message : String(e);
    await setStep(order.id, "check", "failed", message).catch(() => undefined);
    await updateOrder(order.id, { state: "failed" });
    await addEvent(order.id, "failed", `Generation failed: ${message} Nothing was charged beyond the escrow terms; a refund can be requested from Help.`);
  }
}

/** Run one queued order, if any. Returns the order id or null. */
export async function runNext(): Promise<string | null> {
  const order = await claimNextQueued();
  if (!order) return null;
  await processOrder(order);
  return order.id;
}

export async function getOrderPublic(id: string) {
  return getOrder(id);
}
